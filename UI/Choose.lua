local _, TJ = ...
local C = TJ.Content
local T = TJ.T

-------------------------------------------------------------------------------
--  Главная у персонажа без профессий: какую профессию взять.
--  Ремёсла карточками (что делает и какой сбор к нему нужен), ниже - сбор и
--  вторичные профессии.
-------------------------------------------------------------------------------
local CRAFTS = {
  { "alchemy", "Зелья и эликсиры для себя и на продажу. Травы собирает травничество." },
  { "blacksmithing", "Оружие, кольчуга и латы. Руду добывает горное дело." },
  { "enchanting", "Чары на экипировку. Материалы - из распылённых вещей, профессия сбора не нужна." },
  { "engineering", "Бомбы, устройства и ружья. Руду добывает горное дело." },
  { "leatherworking", "Кожаная и кольчужная броня. Шкуры даёт снятие шкур." },
  { "tailoring", "Тканевая броня и сумки. Ткань падает с врагов, профессия сбора не нужна." },
}

function C:BuildChoose(UI)
  local c = UI:Card()
  c:Head({ ring = "Interface\\Icons\\INV_Misc_Book_11" }, T("Какую профессию взять"),
    { { T("Основных профессий можно взять две. Обычно берут ремесло и сбор к нему: сам добываешь - сам создаёшь."), "body" } })
  c:Text(T("Учителя профессий есть в каждой столице и в крупных деревнях."), "small")
  UI:End(c)

  for _, row in ipairs(CRAFTS) do
    local p = TJ.Profs[row[1]]
    if p then
      local pc = UI:Card()
      local lines = { { T(row[2]), "body" } }
      local pair = p.pair and TJ.Profs[p.pair]
      if pair then lines[#lines + 1] = { T("Пара: ") .. TJ:N(pair), "small" } end
      pc:Head({ ring = TJ.Icon(p.icon) }, TJ:N(p), lines, 32)
      UI:End(pc)
    end
  end

  local g = UI:Card()
  g:Head({ ring = "Interface\\Icons\\INV_Misc_Coin_02" }, T("Только сбор"),
    { { T("Две профессии сбора ничего не создают, зато всё собранное можно продать на аукционе. Хороший выбор, если нужно золото."), "body" } }, 32)
  UI:End(g)

  local s = UI:Card()
  s:Head({ ring = "Interface\\Icons\\INV_Misc_Food_15" }, T("Вторичные профессии"),
    { { T("Кулинария, первая помощь и рыбная ловля не занимают место основных - учи все три."), "body" } }, 32)
  s:Text(T("Как только выучишь профессию, здесь появится её маршрут прокачки: что делать сейчас, сколько и из чего."), "small")
  UI:End(s)
end
